#!/usr/bin/env python3
"""Write okhla_import/corrections.sql from the No-SIR cross-check (sir-ocr/okhla_no_sir_crosscheck_59_69.csv).

Two kinds of correction, both found by checking every "No SIR" voter in parts 59-69
against the whole Okhla pack:

  1. SAME PERSON UNDER A RE-ISSUED EPIC — name, relation and age match an ASDD-list entry
     filed under a different (new-series) EPIC. The 2025-roll row becomes ASDD, keeps its
     house, records the new EPIC in alt_epic_norm; the duplicate ASDD-only row is removed.
  2. ADDED AND DELETED IN THE SAME MONTH — the CEO monthly sheet printed the EPIC on both
     the Addition and the Deletion list (the pack discarded the deletion as a "site error")
     and it is absent from the Draft SIR roll: tagged DELETED.

corrections.sql is applied by build_okhla.py after a rebuild and, once, to production with
`wrangler d1 execute --remote --file`. It holds EPICs (PII): git-ignored with the other .sql.
Aggregates (ok_part_status / ok_part_base / ok_parts.electors) are recomputed at the end.
"""
import re
import pandas as pd

HOME = "/Users/khush/Voter Enumeration App"
cc = pd.read_csv(f"{HOME}/sir-ocr/okhla_no_sir_crosscheck_59_69.csv", dtype=str).fillna("")
mon = pd.read_csv(
    f"{HOME}/okhla_pack/Okhla_AC54_SocialAudit/04_Okhla_AC54_Monthly_Additions_Deletions_Modifications_2025-26.csv",
    dtype=str, encoding="utf-8-sig").fillna("")
norm = lambda s: re.sub(r"[^A-Z0-9]", "", s.upper())
q = lambda s: "'" + s.replace("'", "''") + "'"
out = ["-- generated by gen_corrections.py — do not edit"]
n_alias = n_del = 0

for r in cc[cc.verdict.str.startswith("Likely")].itertuples():
    old = norm(r.epic)
    m = re.findall(r"ASDD ([A-Z0-9]+) \(new part (\d+)\)", r.evidence)
    assert len(m) == 1, (old, r.evidence)
    new = m[0][0]
    out += [
        f"UPDATE ok_electors SET status='ASDD', draft_basis=NULL, alt_epic_norm={q(new)}, new_part_src='exact',",
        f"  status_detail=(SELECT status_detail FROM ok_electors u WHERE u.epic_norm={q(new)} AND u.in_2025_roll=0),",
        f"  new_part=(SELECT new_part FROM ok_electors u WHERE u.epic_norm={q(new)} AND u.in_2025_roll=0),",
        f"  conflict={q('Same person as the ASDD-list entry under the re-issued EPIC ' + new + ' (matched on name, relation and age)')}",
        f" WHERE epic_norm={q(old)} AND in_2025_roll=1 AND old_part={int(r.old_part)};",
        f"DELETE FROM ok_tokens WHERE elector_id IN (SELECT id FROM ok_electors WHERE epic_norm={q(new)} AND in_2025_roll=0);",
        f"DELETE FROM ok_electors WHERE epic_norm={q(new)} AND in_2025_roll=0;",
    ]
    n_alias += 1

mon["e"] = mon.epic.map(norm)
for r in cc[cc.verdict.str.startswith("Possibly")].itertuples():
    e = norm(r.epic)
    d = mon[(mon.e == e) & (mon.list_type == "Deletion")]
    assert len(d) >= 1, e
    month = sorted(d.month)[0]
    ml = pd.Timestamp(month + "-01").strftime("%b %Y")
    out.append(
        f"UPDATE ok_electors SET status='DELETED', draft_basis=NULL, deleted_source='monthly', deleted_month={q(month)},"
        f" status_detail={q('Added and deleted in the same month (' + ml + '): the monthly sheet lists it on both the Addition and Deletion lists, and it is not in the Draft SIR roll')}"
        f" WHERE epic_norm={q(e)} AND in_2025_roll=0 AND old_part={int(r.old_part)};"
    )
    n_del += 1

out += [
    "DELETE FROM ok_part_status;",
    "INSERT INTO ok_part_status SELECT old_part, status, COUNT(*) FROM ok_electors WHERE old_part IS NOT NULL GROUP BY old_part, status;",
    "DELETE FROM ok_part_base;",
    """INSERT INTO ok_part_base
 SELECT old_part,
   SUM(CASE WHEN in_2025_roll = 1 AND COALESCE(deleted_source,'') != 'roll_stamp' THEN 1 ELSE 0 END),
   SUM(CASE WHEN in_2025_roll = 1 AND deleted_source = 'roll_stamp' THEN 1 ELSE 0 END),
   SUM(CASE WHEN in_2025_roll = 0 THEN 1 ELSE 0 END),
   SUM(CASE WHEN deleted_source = 'monthly' THEN 1 ELSE 0 END),
   SUM(CASE WHEN status IN ('NOTICE','CLEARED') THEN 1 ELSE 0 END),
   SUM(CASE WHEN status IN ('NOTICE','CLEARED') AND in_2025_roll = 0 THEN 1 ELSE 0 END)
 FROM ok_electors WHERE old_part IS NOT NULL GROUP BY old_part;""",
    "UPDATE ok_parts SET electors = (SELECT COUNT(*) FROM ok_electors e WHERE e.old_part = ok_parts.old_part);",
    f"INSERT OR REPLACE INTO ok_meta VALUES ('corrections_applied', '{n_alias} re-issued EPICs merged into their ASDD record; {n_del} added-and-deleted-same-month tagged deleted');",
]
open(f"{HOME}/electoral_app_cf/okhla_import/corrections.sql", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote corrections.sql: {n_alias} EPIC merges, {n_del} deletions")
