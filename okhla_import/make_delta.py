#!/usr/bin/env python3
"""Build a targeted SQL patch that turns the Okhla register as it stands in PRODUCTION into a
newly rebuilt one — instead of reloading ~4 million rows for a few thousand changed rows.

    python3 okhla_import/make_delta.py --old <copy of the prod-state sqlite> --new <rebuilt sqlite> --out delta.sql

Requires the same row ids in both (a rebuild from the same sources keeps them). Emits one
UPDATE per changed row (by id) for the columns a rebuild can change, then recomputes the
aggregate tables. Output holds voter text (PII) and is git-ignored with the other .sql files.
"""
import argparse, sqlite3

COLS = ["old_part", "status", "status_detail", "deleted_source", "deleted_reason", "deleted_month", "conflict",
        "draft_basis", "new_part", "new_part_src", "draft_serial", "alt_epic_norm",
        "section_no", "section_name", "house_raw", "hh_norm", "hh_key", "hh_sort", "house_floor"]


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", required=True)
    ap.add_argument("--new", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    old, new = sqlite3.connect(a.old), sqlite3.connect(a.new)
    sel = "SELECT id, " + ", ".join(COLS) + " FROM ok_electors"
    O = {r[0]: r[1:] for r in old.execute(sel)}
    N = {r[0]: r[1:] for r in new.execute(sel)}
    assert set(O) == set(N), "row ids differ — a full reload is needed, not a delta"
    out, n = ["-- generated by make_delta.py — do not edit"], 0
    for i in sorted(N):
        if O[i] != N[i]:
            sets = ", ".join(f"{c}={q(v)}" for c, v, ov in zip(COLS, N[i], O[i]) if v != ov)
            out.append(f"UPDATE ok_electors SET {sets} WHERE id={i};")
            n += 1
    # per-part row counts and the build summary come straight from the rebuilt copy
    cols = [c[1] for c in new.execute("PRAGMA table_info(ok_parts)")]
    for r in new.execute("SELECT * FROM ok_parts"):
        out.append("UPDATE ok_parts SET " + f"{cols[5]}={q(r[5])}" + f" WHERE {cols[0]}={q(r[0])};")
    for k, v in new.execute("SELECT key, value FROM ok_meta"):
        out.append(f"INSERT OR REPLACE INTO ok_meta (key, value) VALUES ({q(k)}, {q(v)});")
    out += [
        "DELETE FROM ok_part_status;",
        "INSERT INTO ok_part_status SELECT old_part, status, COUNT(*) FROM ok_electors WHERE old_part IS NOT NULL GROUP BY old_part, status;",
        "DELETE FROM ok_part_base;",
        """INSERT INTO ok_part_base
 SELECT old_part,
   SUM(CASE WHEN in_2025_roll = 1 AND COALESCE(deleted_source,'') != 'roll_stamp' THEN 1 ELSE 0 END),
   SUM(CASE WHEN in_2025_roll = 1 AND deleted_source = 'roll_stamp' THEN 1 ELSE 0 END),
   SUM(CASE WHEN in_2025_roll = 0 THEN 1 ELSE 0 END),
   SUM(CASE WHEN deleted_source = 'monthly' THEN 1 ELSE 0 END),
   SUM(CASE WHEN status IN ('NOTICE','CLEARED') THEN 1 ELSE 0 END),
   SUM(CASE WHEN status IN ('NOTICE','CLEARED') AND in_2025_roll = 0 THEN 1 ELSE 0 END)
 FROM ok_electors WHERE old_part IS NOT NULL GROUP BY old_part;""",
    ]
    open(a.out, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"{n:,} changed rows -> {a.out}")


if __name__ == "__main__":
    main()
